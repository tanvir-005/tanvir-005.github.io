import { writeFileSync } from 'node:fs'
import { profile, cv, entries } from './data.mjs'
const q = (v) => `'${String(v).replace(/'/g, "''")}'`
const lines = ['-- Generated by seed/generate.mjs', 'DELETE FROM entries;']
lines.push(`INSERT INTO settings(key,value) VALUES('profile',${q(JSON.stringify(profile))}) ON CONFLICT(key) DO UPDATE SET value=excluded.value;`)
lines.push(`INSERT INTO settings(key,value) VALUES('cv',${q(JSON.stringify(cv))}) ON CONFLICT(key) DO UPDATE SET value=excluded.value;`)
for (const e of entries) {
  lines.push(`INSERT INTO entries(type,slug,title,summary,body_md,image,date,sort,published,data) VALUES(${[e.type, e.slug, e.title, e.summary, e.body_md, e.image, e.date].map(q).join(',')},${e.sort},${e.published},${q(JSON.stringify(e.data))});`)
}
writeFileSync(new URL('../packages/api/seed.sql', import.meta.url), lines.join('\n') + '\n')
console.log(`seed.sql written: ${entries.length} entries`)
